-- ----- Fecha, año escolar y curso en hora de Chile (el año escolar cambia en marzo)
CREATE FUNCTION app.hoy_chile() RETURNS DATE LANGUAGE sql STABLE AS $$ SELECT (now() AT TIME ZONE 'America/Santiago')::date $$;
CREATE FUNCTION app.anio_escolar(fecha DATE) RETURNS SMALLINT LANGUAGE sql IMMUTABLE AS $$
  SELECT (EXTRACT(YEAR FROM fecha)::int - CASE WHEN EXTRACT(MONTH FROM fecha) < 3 THEN 1 ELSE 0 END)::smallint
$$;
CREATE FUNCTION app.nivel_escolar_en(anio_egreso SMALLINT, fecha DATE) RETURNS SMALLINT LANGUAGE sql STABLE AS $$
  SELECT COALESCE(
    (SELECT id FROM contenido.nivel_escolar WHERE anios_para_egreso = anio_egreso - app.anio_escolar(fecha)),
    CASE WHEN anio_egreso < app.anio_escolar(fecha) THEN (SELECT id FROM contenido.nivel_escolar WHERE codigo = 'EG') END)
$$;

-- ----- Electivo de Ciencias: solo en esa prueba y solo un área con contenidos en ella (Biología, Física o Química)
CREATE FUNCTION contenido.electivo_valido(p_prueba SMALLINT, p_area SMALLINT) RETURNS BOOLEAN LANGUAGE sql STABLE AS $$
  SELECT p_area IS NULL OR ((SELECT codigo FROM contenido.prueba WHERE id = p_prueba) = 'CIE'
         AND EXISTS (SELECT 1 FROM contenido.contenido_tematico WHERE prueba_id = p_prueba AND area_id = p_area))
$$;
CREATE FUNCTION app.tg_estudiante_prueba() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF NOT contenido.electivo_valido(NEW.prueba_id, NEW.electivo_area_id) THEN
    RAISE EXCEPTION 'El electivo solo corresponde a la prueba de Ciencias y debe ser Biología, Física o Química';
  END IF;
  RETURN NEW;
END $$;
