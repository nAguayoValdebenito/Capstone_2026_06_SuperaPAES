-- ----- Evaluaciones
-- Al crear: la base calcula el año escolar y el curso, y valida lo elegido según el tipo y su estructura.
-- Al cambiar: se cierra una sola vez, lo cerrado no cambia y los datos con que se armó no se modifican.
CREATE FUNCTION app.tg_evaluacion() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE t contenido.tipo_evaluacion%ROWTYPE; s contenido.estructura_evaluacion%ROWTYPE; modo TEXT; final BOOLEAN; fecha DATE;
BEGIN
  SELECT * INTO t FROM contenido.tipo_evaluacion WHERE id = NEW.tipo_evaluacion_id;
  SELECT es_final INTO final FROM contenido.estado_evaluacion WHERE id = NEW.estado_evaluacion_id;
  IF TG_OP = 'INSERT' THEN
    SELECT codigo INTO modo FROM contenido.modo_armado WHERE id = t.modo_armado_id;
    SELECT * INTO s FROM contenido.estructura_evaluacion WHERE id = NEW.estructura_id;
    fecha := (NEW.iniciada_en AT TIME ZONE 'America/Santiago')::date;
    NEW.anio_escolar := app.anio_escolar(fecha);
    NEW.nivel_escolar_id := app.nivel_escolar_en((SELECT anio_egreso FROM app.estudiante WHERE id = NEW.estudiante_id), fecha);
    NEW.unica_por_anio_escolar := t.unica_por_anio_escolar;
    IF final THEN RAISE EXCEPTION 'Una evaluación nueva parte en curso'; END IF;
    IF s.id IS NULL OR NOT s.activa THEN RAISE EXCEPTION 'No hay una estructura activa para este tipo de evaluación en esta prueba'; END IF;
    IF NOT t.permite_elegir_alcance AND (NEW.eje_id IS NOT NULL OR NEW.contenido_id IS NOT NULL OR NEW.habilidad_id IS NOT NULL) THEN
      RAISE EXCEPTION 'Este tipo de evaluación no permite elegir eje, contenido ni habilidad';
    END IF;
    IF NOT t.permite_elegir_dificultad AND NEW.dificultad_id IS NOT NULL THEN
      RAISE EXCEPTION 'Este tipo de evaluación no permite elegir dificultad';
    END IF;
    IF t.con_tiempo <> (NEW.duracion_min IS NOT NULL) THEN
      RAISE EXCEPTION 'El tiempo de la evaluación no corresponde a su tipo';
    END IF;
    IF NOT t.entrega_puntaje AND NEW.tabla_conversion_id IS NOT NULL THEN
      RAISE EXCEPTION 'Solo el ensayo completo usa una tabla de conversión';
    END IF;
    IF NOT contenido.electivo_valido(NEW.prueba_id, NEW.electivo_area_id) THEN
      RAISE EXCEPTION 'El electivo solo corresponde a la prueba de Ciencias y debe ser Biología, Física o Química';
    END IF;
    IF NEW.electivo_area_id IS NULL AND EXISTS (SELECT 1 FROM contenido.estructura_detalle WHERE estructura_id = s.id AND es_electivo) THEN
      RAISE EXCEPTION 'Esta evaluación tiene módulo electivo: el estudiante debe elegir su electivo antes de empezar';
    END IF;
    IF NEW.tabla_conversion_id IS NOT NULL AND (SELECT electivo_area_id FROM contenido.tabla_conversion WHERE id = NEW.tabla_conversion_id)
       IS DISTINCT FROM NEW.electivo_area_id THEN
      RAISE EXCEPTION 'La tabla de conversión debe ser la del electivo de la evaluación';
    END IF;
    IF NEW.cantidad_preguntas > s.cantidad_max OR (modo = 'adaptativo' AND NEW.cantidad_preguntas < s.cantidad_min) THEN
      RAISE EXCEPTION 'La cantidad de preguntas debe estar entre % y %', s.cantidad_min, s.cantidad_max;
    END IF;
    RETURN NEW;
  END IF;
  IF OLD.cerrada_en IS NOT NULL THEN RAISE EXCEPTION 'Una evaluación cerrada no se modifica'; END IF;
  IF final <> (NEW.cerrada_en IS NOT NULL) THEN
    RAISE EXCEPTION 'Una evaluación cerrada debe tener un estado final y una fecha de cierre';
  END IF;
  IF (NEW.estudiante_id, NEW.tipo_evaluacion_id, NEW.prueba_id, NEW.estructura_id, NEW.eje_id, NEW.contenido_id, NEW.habilidad_id, NEW.dificultad_id, NEW.electivo_area_id,
      NEW.nivel_escolar_id, NEW.anio_escolar, NEW.tabla_conversion_id, NEW.cantidad_preguntas, NEW.duracion_min, NEW.iniciada_en, NEW.vence_en)
     IS DISTINCT FROM
     (OLD.estudiante_id, OLD.tipo_evaluacion_id, OLD.prueba_id, OLD.estructura_id, OLD.eje_id, OLD.contenido_id, OLD.habilidad_id, OLD.dificultad_id, OLD.electivo_area_id,
      OLD.nivel_escolar_id, OLD.anio_escolar, OLD.tabla_conversion_id, OLD.cantidad_preguntas, OLD.duracion_min, OLD.iniciada_en, OLD.vence_en) THEN
    RAISE EXCEPTION 'Los datos con que se armó la evaluación no se modifican';
  END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER evaluacion_reglas BEFORE INSERT OR UPDATE ON app.evaluacion
  FOR EACH ROW EXECUTE FUNCTION app.tg_evaluacion();

-- Cada pregunta de la evaluación: solo la versión vigente de una pregunta publicada, de la misma prueba, de lo elegido (eje, contenido, habilidad o dificultad),
-- de un contenido ya visto si el tipo filtra por curso, y sin pasarse de la cantidad. Responder solo con la evaluación
-- abierta y dentro del tiempo; cambiar la respuesta solo si el tipo lo permite. La corrección la calcula siempre la base.
CREATE FUNCTION app.tg_item() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE e app.evaluacion%ROWTYPE; t contenido.tipo_evaluacion%ROWTYPE; s contenido.estructura_evaluacion%ROWTYPE;
        v contenido.pregunta_version%ROWTYPE; modo TEXT; nivel_contenido SMALLINT; nivel_estudiante SMALLINT;
BEGIN
  SELECT * INTO e FROM app.evaluacion WHERE id = NEW.evaluacion_id;
  SELECT * INTO t FROM contenido.tipo_evaluacion WHERE id = e.tipo_evaluacion_id;
  SELECT * INTO v FROM contenido.pregunta_version WHERE pregunta_id = NEW.pregunta_id AND version = NEW.version_pregunta;
  IF TG_OP = 'INSERT' THEN
    SELECT codigo INTO modo FROM contenido.modo_armado WHERE id = t.modo_armado_id;
    SELECT * INTO s FROM contenido.estructura_evaluacion WHERE id = e.estructura_id;
    IF e.cerrada_en IS NOT NULL THEN RAISE EXCEPTION 'No se agregan preguntas a una evaluación cerrada'; END IF;
    IF NEW.orden > e.cantidad_preguntas THEN RAISE EXCEPTION 'La evaluación ya tiene todas sus preguntas'; END IF;
    IF NOT EXISTS (SELECT 1 FROM contenido.pregunta p JOIN contenido.estado_pregunta ep ON ep.id = p.estado_pregunta_id
                   WHERE p.id = NEW.pregunta_id AND ep.visible_estudiante AND p.version = NEW.version_pregunta) THEN
      RAISE EXCEPTION 'Solo se entrega la versión vigente de una pregunta publicada';
    END IF;
    IF (e.eje_id IS NOT NULL AND v.eje_id <> e.eje_id) OR (e.contenido_id IS NOT NULL AND v.contenido_id <> e.contenido_id)
       OR (e.habilidad_id IS NOT NULL AND v.habilidad_id <> e.habilidad_id) OR (e.dificultad_id IS NOT NULL AND v.dificultad_id <> e.dificultad_id) THEN
      RAISE EXCEPTION 'La pregunta no corresponde al eje, contenido, habilidad o dificultad elegidos';
    END IF;
    IF t.filtra_por_nivel AND e.nivel_escolar_id IS NOT NULL THEN
      SELECT n.orden INTO nivel_contenido FROM contenido.contenido_tematico c JOIN contenido.nivel_escolar n ON n.id = c.nivel_escolar_id WHERE c.id = v.contenido_id;
      SELECT orden INTO nivel_estudiante FROM contenido.nivel_escolar WHERE id = e.nivel_escolar_id;
      IF nivel_contenido > nivel_estudiante THEN RAISE EXCEPTION 'La pregunta es de un contenido que el estudiante aún no ha visto'; END IF;
    END IF;
    IF modo = 'falladas' AND NOT EXISTS (SELECT 1 FROM app.v_preguntas_falladas f WHERE f.estudiante_id = e.estudiante_id AND f.pregunta_id = NEW.pregunta_id) THEN
      RAISE EXCEPTION 'El repaso solo entrega preguntas que el estudiante falló u omitió';
    END IF;
    IF NOT NEW.puntuable AND (NOT t.entrega_puntaje OR
       (SELECT COUNT(*) FROM app.evaluacion_item WHERE evaluacion_id = NEW.evaluacion_id AND NOT puntuable) >= s.no_puntuables) THEN
      RAISE EXCEPTION 'La evaluación ya tiene todas sus preguntas sin puntaje';
    END IF;
  END IF;
  IF NEW.alternativa_id IS DISTINCT FROM (CASE WHEN TG_OP = 'UPDATE' THEN OLD.alternativa_id END) THEN
    IF e.cerrada_en IS NOT NULL THEN RAISE EXCEPTION 'La evaluación está cerrada'; END IF;
    IF e.vence_en IS NOT NULL AND now() > e.vence_en + INTERVAL '10 seconds' THEN
      RAISE EXCEPTION 'Se acabó el tiempo de la evaluación';
    END IF;
    IF TG_OP = 'UPDATE' AND OLD.alternativa_id IS NOT NULL THEN
      IF NOT t.permite_cambiar_respuesta THEN RAISE EXCEPTION 'En este tipo de evaluación la respuesta no se cambia'; END IF;
      NEW.veces_cambiada := OLD.veces_cambiada + 1;
    END IF;
    IF NEW.alternativa_id IS NOT NULL AND (TG_OP = 'INSERT' OR OLD.alternativa_id IS NULL) THEN
      IF t.consume_cupo AND NEW.tipo_consumo_id IS NULL THEN RAISE EXCEPTION 'Falta indicar qué se descontó al responder'; END IF;
    END IF;
    UPDATE app.evaluacion SET ultima_actividad_en = now() WHERE id = e.id AND cerrada_en IS NULL;
  END IF;
  IF NOT t.consume_cupo AND NEW.tipo_consumo_id IS NOT NULL THEN
    RAISE EXCEPTION 'Este tipo de evaluación no descuenta cupo';
  END IF;
  IF TG_OP = 'UPDATE' AND e.cerrada_en IS NOT NULL
     AND (NEW.alternativa_id, NEW.respondida_en, NEW.tiempo_seg, NEW.puntuable, NEW.pregunta_id, NEW.version_pregunta, NEW.tipo_consumo_id)
         IS DISTINCT FROM (OLD.alternativa_id, OLD.respondida_en, OLD.tiempo_seg, OLD.puntuable, OLD.pregunta_id, OLD.version_pregunta, OLD.tipo_consumo_id) THEN
    RAISE EXCEPTION 'Las respuestas de una evaluación cerrada no se modifican';
  END IF;
  IF t.correccion_inmediata THEN
    NEW.es_correcta := CASE WHEN NEW.alternativa_id IS NULL THEN NULL ELSE NEW.alternativa_id = v.alternativa_correcta_id END;
  ELSIF e.cerrada_en IS NULL THEN
    NEW.es_correcta := NULL;
  ELSE
    NEW.es_correcta := COALESCE(NEW.alternativa_id = v.alternativa_correcta_id, false);
  END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER item_reglas BEFORE INSERT OR UPDATE ON app.evaluacion_item
  FOR EACH ROW EXECUTE FUNCTION app.tg_item();

