-- Supera PAES. Modelo de datos relacional, versión 11.0 (misma numeración que el documento del modelo)
-- Cambios respecto de la 10.0: código de verificación de 6 dígitos con sus intentos y anulación del correo anterior al pedir uno nuevo
-- (RN-32); módulo común y módulo electivo de Ciencias en la estructura de evaluación, con sus preguntas sin puntaje (RN-35); tablas
-- de conversión por electivo de Ciencias, completas y sin saltos; puntaje estimado aunque se anule una pregunta; formato del código
-- de invitación (RN-33); racha calculada por la base al responder (RF-A05); versión mayor.menor de los documentos legales (RN-30); y
-- datos iniciales con la mezcla 30/45/25 (RN-09), los productos de cada tienda, el reparto por eje y las tablas de conversión.
-- Script de creación para PostgreSQL 18 (compatible con PostgreSQL 16 o superior).

CREATE SCHEMA IF NOT EXISTS contenido;
CREATE SCHEMA IF NOT EXISTS app;

