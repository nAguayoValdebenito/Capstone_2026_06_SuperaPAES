CREATE TABLE contenido.nivel_escolar (
  id SMALLINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  codigo VARCHAR(4) NOT NULL UNIQUE,
  nombre VARCHAR(60) NOT NULL,
  orden SMALLINT NOT NULL UNIQUE,
  anios_para_egreso SMALLINT UNIQUE,
  PRIMARY KEY (id)
);

CREATE TABLE contenido.dificultad (
  id SMALLINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  codigo VARCHAR(10) NOT NULL UNIQUE,
  nombre VARCHAR(60) NOT NULL,
  orden SMALLINT NOT NULL UNIQUE,
  peso NUMERIC(3,2) NOT NULL CHECK (peso > 0),
  mezcla_min SMALLINT NOT NULL,
  mezcla_objetivo SMALLINT NOT NULL,
  mezcla_max SMALLINT NOT NULL,
  acierto_esperado_min SMALLINT NOT NULL,
  acierto_esperado_max SMALLINT NOT NULL,
  PRIMARY KEY (id),
  CHECK (0 <= mezcla_min AND mezcla_min <= mezcla_objetivo AND mezcla_objetivo <= mezcla_max AND mezcla_max <= 100),
  CHECK (0 <= acierto_esperado_min AND acierto_esperado_min < acierto_esperado_max AND acierto_esperado_max <= 100)
);

