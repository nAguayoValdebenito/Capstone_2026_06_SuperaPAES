-- ----- Ciclo de vida de la pregunta
-- Parte en la etapa inicial; solo cambia según las transiciones permitidas y cada cambio queda en el historial.
-- No se edita fuera de una etapa editable; si se edita una versión ya guardada, la versión sube sola.
-- Al entrar en una etapa que guarda versión (en revisión, publicada) se guarda la copia fija con su clave y su clasificación.
-- Solo se publica una pregunta completa, con dificultad asignada y, si es de la IA, con la explicación de cada alternativa.
CREATE FUNCTION contenido.tg_pregunta() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE
  hacia contenido.estado_pregunta%ROWTYPE;
  desde contenido.estado_pregunta%ROWTYPE;
  p contenido.prueba%ROWTYPE;
  n_alt SMALLINT; n_ok SMALLINT; n_sin_expl SMALLINT; correcta BIGINT; eje SMALLINT; nueva JSONB; existente JSONB;
BEGIN
  SELECT * INTO hacia FROM contenido.estado_pregunta WHERE id = NEW.estado_pregunta_id;
  IF TG_OP = 'INSERT' THEN
    IF NOT hacia.es_inicial THEN RAISE EXCEPTION 'Una pregunta nueva parte en la etapa inicial'; END IF;
    RETURN NEW;
  END IF;
  SELECT * INTO desde FROM contenido.estado_pregunta WHERE id = OLD.estado_pregunta_id;
  IF (NEW.prueba_id, NEW.contenido_id, NEW.habilidad_id, NEW.tipo_pregunta_id, NEW.texto_estimulo_id, NEW.orden_en_texto, NEW.enunciado, NEW.explicacion)
     IS DISTINCT FROM (OLD.prueba_id, OLD.contenido_id, OLD.habilidad_id, OLD.tipo_pregunta_id, OLD.texto_estimulo_id, OLD.orden_en_texto, OLD.enunciado, OLD.explicacion) THEN
    IF NOT desde.editable THEN RAISE EXCEPTION 'La pregunta no se puede editar en la etapa %', desde.codigo; END IF;
    IF NEW.version = OLD.version AND EXISTS (SELECT 1 FROM contenido.pregunta_version WHERE pregunta_id = OLD.id AND version = OLD.version) THEN
      NEW.version := OLD.version + 1;
    END IF;
  ELSIF NEW.version < OLD.version THEN
    RAISE EXCEPTION 'La versión de una pregunta no retrocede';
  END IF;
  IF NEW.estado_pregunta_id IS DISTINCT FROM OLD.estado_pregunta_id THEN
    IF NOT EXISTS (SELECT 1 FROM contenido.transicion_estado_pregunta WHERE desde_id = OLD.estado_pregunta_id AND hacia_id = NEW.estado_pregunta_id) THEN
      RAISE EXCEPTION 'Cambio de etapa no permitido: de % a %', desde.codigo, hacia.codigo;
    END IF;
    INSERT INTO contenido.historial_estado_pregunta (pregunta_id, desde_id, hacia_id, version, usuario_id)
      VALUES (NEW.id, OLD.estado_pregunta_id, NEW.estado_pregunta_id, NEW.version, NULLIF(current_setting('supera.usuario_id', true), '')::bigint);
    IF hacia.guarda_version THEN
      SELECT * INTO p FROM contenido.prueba WHERE id = NEW.prueba_id;
      SELECT COUNT(*), COUNT(*) FILTER (WHERE es_correcta), MAX(id) FILTER (WHERE es_correcta), COUNT(*) FILTER (WHERE explicacion IS NULL)
        INTO n_alt, n_ok, correcta, n_sin_expl FROM contenido.alternativa WHERE pregunta_id = NEW.id;
      IF n_ok <> 1 OR n_alt < p.opciones_min OR n_alt > p.opciones_max THEN
        RAISE EXCEPTION 'La pregunta debe tener entre % y % alternativas y una sola correcta', p.opciones_min, p.opciones_max;
      END IF;
      IF p.textos IS NOT NULL AND NEW.texto_estimulo_id IS NULL THEN
        RAISE EXCEPTION 'En esta prueba cada pregunta va asociada a un texto';
      END IF;
      IF hacia.visible_estudiante THEN
        IF NEW.dificultad_asignada_id IS NULL THEN RAISE EXCEPTION 'Solo se publica una pregunta con dificultad asignada por los docentes'; END IF;
        IF NEW.lote_id IS NOT NULL AND n_sin_expl > 0 THEN RAISE EXCEPTION 'Una pregunta de la IA se publica con la explicación de cada alternativa'; END IF;
        NEW.publicado_en := now();
      END IF;
      SELECT eje_id INTO eje FROM contenido.contenido_tematico WHERE id = NEW.contenido_id;
      nueva := jsonb_build_object('enunciado', NEW.enunciado, 'explicacion', NEW.explicacion, 'texto_estimulo_id', NEW.texto_estimulo_id,
                 'alternativas', (SELECT jsonb_agg(jsonb_build_object('id', id, 'letra', letra, 'texto', texto, 'explicacion', explicacion) ORDER BY letra)
                                  FROM contenido.alternativa WHERE pregunta_id = NEW.id));
      SELECT copia INTO existente FROM contenido.pregunta_version WHERE pregunta_id = NEW.id AND version = NEW.version;
      IF existente IS NULL THEN
        INSERT INTO contenido.pregunta_version (pregunta_id, version, copia, alternativa_correcta_id, cantidad_alternativas, eje_id, contenido_id,
                                                habilidad_id, dificultad_id, editado_por)
        VALUES (NEW.id, NEW.version, nueva, correcta, n_alt, eje, NEW.contenido_id, NEW.habilidad_id,
                CASE WHEN hacia.visible_estudiante THEN NEW.dificultad_asignada_id END, NULLIF(current_setting('supera.usuario_id', true), '')::bigint);
      ELSIF existente <> nueva THEN
        RAISE EXCEPTION 'La versión % ya fue guardada con otro contenido', NEW.version;
      ELSIF hacia.visible_estudiante THEN
        UPDATE contenido.pregunta_version SET dificultad_id = NEW.dificultad_asignada_id WHERE pregunta_id = NEW.id AND version = NEW.version;
      END IF;
    END IF;
  END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER pregunta_reglas BEFORE INSERT OR UPDATE ON contenido.pregunta
  FOR EACH ROW EXECUTE FUNCTION contenido.tg_pregunta();
-- La creación de la pregunta también queda en el historial (después de insertarla, cuando su fila ya existe).
CREATE FUNCTION contenido.tg_pregunta_creada() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  INSERT INTO contenido.historial_estado_pregunta (pregunta_id, desde_id, hacia_id, version, usuario_id)
    VALUES (NEW.id, NULL, NEW.estado_pregunta_id, NEW.version, NULLIF(current_setting('supera.usuario_id', true), '')::bigint);
  RETURN NULL;
END $$;
CREATE TRIGGER pregunta_creada AFTER INSERT ON contenido.pregunta
  FOR EACH ROW EXECUTE FUNCTION contenido.tg_pregunta_creada();

-- Las alternativas solo cambian si la pregunta está en una etapa editable; si su versión ya fue guardada, la versión sube.
CREATE FUNCTION contenido.tg_alternativa() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE pid BIGINT := COALESCE(NEW.pregunta_id, OLD.pregunta_id); editable BOOLEAN; v INTEGER;
BEGIN
  SELECT e.editable, p.version INTO editable, v FROM contenido.pregunta p JOIN contenido.estado_pregunta e ON e.id = p.estado_pregunta_id WHERE p.id = pid;
  IF NOT editable THEN RAISE EXCEPTION 'Las alternativas no se pueden cambiar en la etapa actual de la pregunta'; END IF;
  IF EXISTS (SELECT 1 FROM contenido.pregunta_version WHERE pregunta_id = pid AND version = v) THEN
    UPDATE contenido.pregunta SET version = version + 1 WHERE id = pid;
  END IF;
  RETURN COALESCE(NEW, OLD);
END $$;
CREATE TRIGGER alternativa_reglas BEFORE INSERT OR UPDATE OR DELETE ON contenido.alternativa
  FOR EACH ROW EXECUTE FUNCTION contenido.tg_alternativa();

-- ----- Revisión: la decisión que lo requiere lleva comentario
CREATE FUNCTION contenido.tg_revision() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF NEW.comentario IS NULL AND (SELECT requiere_comentario FROM contenido.decision_revision WHERE id = NEW.decision_revision_id) THEN
    RAISE EXCEPTION 'Esta decisión requiere un comentario';
  END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER revision_reglas BEFORE INSERT OR UPDATE ON contenido.revision
  FOR EACH ROW EXECUTE FUNCTION contenido.tg_revision();

-- ----- Estructura: el reparto es de la misma prueba y suma la cantidad de la estructura. El módulo electivo solo existe
-- en Ciencias, y si el reparto indica preguntas sin puntaje, suman las de la estructura (RN-35).
CREATE FUNCTION contenido.tg_estructura_suma() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE e contenido.estructura_evaluacion%ROWTYPE; total INTEGER; total_np INTEGER;
BEGIN
  SELECT * INTO e FROM contenido.estructura_evaluacion WHERE id = COALESCE(NEW.estructura_id, OLD.estructura_id);
  IF e.prueba_id <> COALESCE(NEW.prueba_id, OLD.prueba_id) THEN
    RAISE EXCEPTION 'El reparto debe ser de la misma prueba que la estructura';
  END IF;
  IF TG_OP <> 'DELETE' AND NEW.es_electivo AND (SELECT codigo FROM contenido.prueba WHERE id = NEW.prueba_id) <> 'CIE' THEN
    RAISE EXCEPTION 'El módulo electivo solo existe en la prueba de Ciencias';
  END IF;
  SELECT SUM(cantidad), SUM(no_puntuables) INTO total, total_np FROM contenido.estructura_detalle WHERE estructura_id = e.id;
  IF total IS NOT NULL AND total <> e.cantidad_max THEN
    RAISE EXCEPTION 'El reparto suma % preguntas y la estructura pide %', total, e.cantidad_max;
  END IF;
  IF total_np > 0 AND total_np <> e.no_puntuables THEN
    RAISE EXCEPTION 'El reparto indica % preguntas sin puntaje y la estructura pide %', total_np, e.no_puntuables;
  END IF;
  RETURN NULL;
END $$;
