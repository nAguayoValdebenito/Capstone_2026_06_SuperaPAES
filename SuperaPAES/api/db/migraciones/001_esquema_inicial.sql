-- ----- Preguntas extra: un abono nace de una invitación verificada de quien invitó, y un consumo de una respuesta suya
-- descontada de las preguntas extra. El saldo (abonos menos consumos) nunca queda negativo.
CREATE FUNCTION app.tg_movimiento_bono() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE tm contenido.tipo_movimiento_bono%ROWTYPE;
BEGIN
  SELECT * INTO tm FROM contenido.tipo_movimiento_bono WHERE id = NEW.tipo_movimiento_bono_id;
  IF tm.requiere_invitacion <> (NEW.invitacion_id IS NOT NULL) THEN
    RAISE EXCEPTION 'Un abono nace de una invitación y un consumo de una respuesta';
  END IF;
  IF NEW.invitacion_id IS NOT NULL AND NOT EXISTS (SELECT 1 FROM app.invitacion WHERE id = NEW.invitacion_id AND invitante_id = NEW.estudiante_id AND verificado_en IS NOT NULL) THEN
    RAISE EXCEPTION 'El abono es para quien invitó y solo cuando la persona invitada verificó su correo';
  END IF;
  IF NEW.evaluacion_item_id IS NOT NULL AND NOT EXISTS (
       SELECT 1 FROM app.evaluacion_item i JOIN app.evaluacion e ON e.id = i.evaluacion_id
        WHERE i.id = NEW.evaluacion_item_id AND e.estudiante_id = NEW.estudiante_id
          AND i.tipo_consumo_id = (SELECT id FROM contenido.tipo_consumo WHERE codigo = 'bono')) THEN
    RAISE EXCEPTION 'El consumo corresponde a una respuesta del mismo estudiante descontada de las preguntas extra';
  END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER movimiento_bono_reglas BEFORE INSERT OR UPDATE ON app.movimiento_bono
  FOR EACH ROW EXECUTE FUNCTION app.tg_movimiento_bono();

-- Revisa el saldo después de cada cambio. Se bloquea la fila del estudiante para que dos consumos al mismo tiempo
-- no dejen el saldo bajo cero.
CREATE FUNCTION app.tg_saldo_bono() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE est BIGINT; saldo INTEGER;
BEGIN
  FOREACH est IN ARRAY ARRAY[CASE WHEN TG_OP <> 'DELETE' THEN NEW.estudiante_id END, CASE WHEN TG_OP <> 'INSERT' THEN OLD.estudiante_id END] LOOP
    CONTINUE WHEN est IS NULL;
    PERFORM 1 FROM app.estudiante WHERE id = est FOR UPDATE;
    SELECT COALESCE(SUM(t.signo * m.cantidad), 0) INTO saldo
      FROM app.movimiento_bono m JOIN contenido.tipo_movimiento_bono t ON t.id = m.tipo_movimiento_bono_id
     WHERE m.estudiante_id = est;
    IF saldo < 0 THEN RAISE EXCEPTION 'El saldo de preguntas extra no alcanza'; END IF;
  END LOOP;
  RETURN NULL;
END $$;
CREATE TRIGGER movimiento_bono_saldo AFTER INSERT OR UPDATE OR DELETE ON app.movimiento_bono
  FOR EACH ROW EXECUTE FUNCTION app.tg_saldo_bono();

-- Calcula y guarda el resultado de una evaluación cerrada: totales, puntaje (solo con tabla de conversión) y desglose.
-- Las preguntas sin puntaje y las anuladas no cuentan. En práctica y repaso cuentan las respondidas.
-- El puntaje sale de la tabla de conversión. Si las preguntas que cuentan no son tantas como el máximo de la tabla (por ejemplo,
-- porque se anuló una pregunta o porque el DEMRE eliminó una de su forma), las correctas se llevan a la escala de la tabla.
CREATE FUNCTION app.calcular_resultado(p_id BIGINT) RETURNS void LANGUAGE plpgsql AS $$
DECLARE e app.evaluacion%ROWTYPE; t contenido.tipo_evaluacion%ROWTYPE;
        n_punt INTEGER; n_ok INTEGER; n_mal INTEGER; n_omit INTEGER; maximo INTEGER; p_equiv INTEGER; v_puntaje SMALLINT;
BEGIN
  SELECT * INTO e FROM app.evaluacion WHERE id = p_id;
  SELECT * INTO t FROM contenido.tipo_evaluacion WHERE id = e.tipo_evaluacion_id;
  SELECT COUNT(*), COUNT(*) FILTER (WHERE es_correcta), COUNT(*) FILTER (WHERE alternativa_id IS NOT NULL AND NOT es_correcta),
         COUNT(*) FILTER (WHERE alternativa_id IS NULL)
    INTO n_punt, n_ok, n_mal, n_omit
    FROM app.evaluacion_item i
   WHERE i.evaluacion_id = p_id AND i.puntuable AND NOT i.anulada AND (NOT t.correccion_inmediata OR i.alternativa_id IS NOT NULL);
  IF e.tabla_conversion_id IS NOT NULL AND n_punt > 0 THEN
    SELECT MAX(correctas) INTO maximo FROM contenido.tabla_conversion_fila WHERE tabla_conversion_id = e.tabla_conversion_id;
    p_equiv := CASE WHEN n_punt = maximo THEN n_ok ELSE ROUND(n_ok::numeric * maximo / n_punt)::int END;
    SELECT puntaje INTO v_puntaje FROM contenido.tabla_conversion_fila WHERE tabla_conversion_id = e.tabla_conversion_id AND correctas = p_equiv;
  END IF;
  INSERT INTO app.resultado_evaluacion AS r (evaluacion_id, puntuables, correctas, incorrectas, omitidas, porcentaje, tabla_conversion_id, puntaje, tiempo_usado_seg)
  VALUES (p_id, n_punt, n_ok, n_mal, n_omit, COALESCE(ROUND(100.0 * n_ok / NULLIF(n_punt, 0), 1), 0),
          CASE WHEN v_puntaje IS NOT NULL THEN e.tabla_conversion_id END, v_puntaje,
          EXTRACT(EPOCH FROM (e.cerrada_en - e.iniciada_en))::int)
  ON CONFLICT (evaluacion_id) DO UPDATE SET puntuables = EXCLUDED.puntuables, correctas = EXCLUDED.correctas, incorrectas = EXCLUDED.incorrectas,
     omitidas = EXCLUDED.omitidas, porcentaje = EXCLUDED.porcentaje, tabla_conversion_id = EXCLUDED.tabla_conversion_id,
     puntaje = EXCLUDED.puntaje, recalculado_en = now();
  DELETE FROM app.resultado_eje WHERE evaluacion_id = p_id;
  DELETE FROM app.resultado_habilidad WHERE evaluacion_id = p_id;
  INSERT INTO app.resultado_eje
  SELECT p_id, v.eje_id, COUNT(*), COUNT(*) FILTER (WHERE i.es_correcta)
    FROM app.evaluacion_item i JOIN contenido.pregunta_version v ON (v.pregunta_id, v.version) = (i.pregunta_id, i.version_pregunta)
   WHERE i.evaluacion_id = p_id AND i.puntuable AND NOT i.anulada AND i.es_correcta IS NOT NULL
   GROUP BY v.eje_id;
  INSERT INTO app.resultado_habilidad
  SELECT p_id, v.habilidad_id, COUNT(*), COUNT(*) FILTER (WHERE i.es_correcta)
    FROM app.evaluacion_item i JOIN contenido.pregunta_version v ON (v.pregunta_id, v.version) = (i.pregunta_id, i.version_pregunta)
   WHERE i.evaluacion_id = p_id AND i.puntuable AND NOT i.anulada AND i.es_correcta IS NOT NULL
   GROUP BY v.habilidad_id;
END $$;

-- Cierra una evaluación, la corrige y guarda su resultado en una sola transacción. Si se acabó el tiempo, el cierre
-- queda en la hora de término. Un diagnóstico abandonado también se corrige, con lo no respondido como omitido.
CREATE FUNCTION app.cerrar_evaluacion(p_id BIGINT, p_estado VARCHAR) RETURNS void LANGUAGE plpgsql AS $$
DECLARE estado contenido.estado_evaluacion%ROWTYPE; e app.evaluacion%ROWTYPE;
BEGIN
  SELECT * INTO estado FROM contenido.estado_evaluacion WHERE codigo = p_estado;
  IF estado.id IS NULL OR NOT estado.es_final THEN RAISE EXCEPTION 'Estado de cierre no válido: %', p_estado; END IF;
  SELECT * INTO e FROM app.evaluacion WHERE id = p_id FOR UPDATE;
  IF e.cerrada_en IS NOT NULL THEN RAISE EXCEPTION 'La evaluación ya está cerrada'; END IF;
  UPDATE app.evaluacion SET estado_evaluacion_id = estado.id, cerrada_en = LEAST(now(), COALESCE(vence_en, now())) WHERE id = p_id;
  UPDATE app.evaluacion_item SET es_correcta = es_correcta WHERE evaluacion_id = p_id;  -- el disparador corrige con la clave
  PERFORM app.calcular_resultado(p_id);
END $$;

-- Cierra las evaluaciones con el tiempo cumplido (tiempo agotado) y las prácticas sin actividad (abandonadas).
-- La ejecuta una tarea periódica de la API. Devuelve cuántas cerró.
CREATE FUNCTION app.cerrar_vencidas() RETURNS INTEGER LANGUAGE plpgsql AS $$
DECLARE r RECORD; n INTEGER := 0;
        horas NUMERIC := (SELECT (valor #>> '{}')::numeric FROM contenido.configuracion WHERE clave = 'horas_inactividad_practica');
BEGIN
  FOR r IN SELECT id FROM app.evaluacion WHERE cerrada_en IS NULL AND vence_en < now() FOR UPDATE SKIP LOCKED LOOP
    PERFORM app.cerrar_evaluacion(r.id, 'tiempo_agotado'); n := n + 1;
  END LOOP;
  FOR r IN SELECT ev.id FROM app.evaluacion ev JOIN contenido.tipo_evaluacion t ON t.id = ev.tipo_evaluacion_id
            WHERE ev.cerrada_en IS NULL AND NOT t.con_tiempo AND ev.ultima_actividad_en < now() - horas * INTERVAL '1 hour'
            FOR UPDATE OF ev SKIP LOCKED LOOP
    PERFORM app.cerrar_evaluacion(r.id, 'abandonada'); n := n + 1;
  END LOOP;
  RETURN n;
END $$;

-- Anula una pregunta con error: deja de entregarse, no cuenta en ningún resultado y los resultados afectados se recalculan.
-- No borra nada. Devuelve cuántas evaluaciones cerradas se recalcularon.
CREATE FUNCTION app.anular_pregunta(p_pregunta_id BIGINT) RETURNS INTEGER LANGUAGE plpgsql AS $$
DECLARE r RECORD; n INTEGER := 0; retirada SMALLINT := (SELECT id FROM contenido.estado_pregunta WHERE codigo = 'retirada');
BEGIN
  UPDATE contenido.pregunta p SET estado_pregunta_id = retirada
   WHERE p.id = p_pregunta_id AND (SELECT visible_estudiante FROM contenido.estado_pregunta WHERE id = p.estado_pregunta_id);
  UPDATE app.evaluacion_item SET anulada = true WHERE pregunta_id = p_pregunta_id AND NOT anulada;
  FOR r IN SELECT DISTINCT ev.id FROM app.evaluacion ev JOIN app.evaluacion_item i ON i.evaluacion_id = ev.id
            WHERE i.pregunta_id = p_pregunta_id AND ev.cerrada_en IS NOT NULL LOOP
    PERFORM app.calcular_resultado(r.id); n := n + 1;
  END LOOP;
  RETURN n;
END $$;

