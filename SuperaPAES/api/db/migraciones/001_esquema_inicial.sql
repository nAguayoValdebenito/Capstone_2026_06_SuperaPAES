CREATE TABLE contenido.rol (
  id SMALLINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  codigo VARCHAR(10) NOT NULL UNIQUE,
  nombre VARCHAR(60) NOT NULL,
  descripcion VARCHAR(200) NOT NULL,
