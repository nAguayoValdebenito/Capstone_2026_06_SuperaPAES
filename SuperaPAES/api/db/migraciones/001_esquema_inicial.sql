  no_puntuables SMALLINT NOT NULL DEFAULT 0 CHECK (no_puntuables >= 0),
  duracion_min SMALLINT CHECK (duracion_min > 0),
  textos SMALLINT CHECK (textos > 0),
  usos_gratis_mes SMALLINT NOT NULL DEFAULT 0 CHECK (usos_gratis_mes >= 0),
