  id INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  estructura_id INTEGER NOT NULL,
  prueba_id SMALLINT NOT NULL,
  eje_id SMALLINT,
  habilidad_id SMALLINT,
  es_electivo BOOLEAN NOT NULL DEFAULT false,
  cantidad SMALLINT NOT NULL CHECK (cantidad > 0),
  no_puntuables SMALLINT NOT NULL DEFAULT 0 CHECK (no_puntuables >= 0),
  PRIMARY KEY (id),
  UNIQUE (estructura_id, eje_id),
  UNIQUE (estructura_id, habilidad_id),
  CHECK (num_nonnulls(eje_id, habilidad_id) = CASE WHEN es_electivo THEN 0 ELSE 1 END),
  CHECK (no_puntuables < cantidad)
);

