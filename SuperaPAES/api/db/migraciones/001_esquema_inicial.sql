-- ----- Tablas de conversión: en Ciencias son por electivo y en las demás pruebas no; cada tabla va de 0 al máximo de
-- correctas sin saltos, sin pasar de las preguntas que cuentan en la prueba, y el puntaje nunca baja.
CREATE FUNCTION contenido.tg_tabla_conversion() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF ((SELECT codigo FROM contenido.prueba WHERE id = NEW.prueba_id) = 'CIE') <> (NEW.electivo_area_id IS NOT NULL)
     OR NOT contenido.electivo_valido(NEW.prueba_id, NEW.electivo_area_id) THEN
    RAISE EXCEPTION 'En Ciencias cada tabla es de un electivo (Biología, Física o Química); en las demás pruebas no lleva electivo';
  END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER tabla_conversion_reglas BEFORE INSERT OR UPDATE ON contenido.tabla_conversion
  FOR EACH ROW EXECUTE FUNCTION contenido.tg_tabla_conversion();
CREATE FUNCTION contenido.tg_tabla_conversion_fila() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE tid INTEGER; n INTEGER; maximo INTEGER; tope SMALLINT; bajan INTEGER;
BEGIN
  FOREACH tid IN ARRAY ARRAY[CASE WHEN TG_OP <> 'DELETE' THEN NEW.tabla_conversion_id END, CASE WHEN TG_OP <> 'INSERT' THEN OLD.tabla_conversion_id END] LOOP
    CONTINUE WHEN tid IS NULL;
    SELECT COUNT(*), MAX(correctas) INTO n, maximo FROM contenido.tabla_conversion_fila WHERE tabla_conversion_id = tid;
    CONTINUE WHEN n = 0;
    SELECT p.preguntas_puntuables INTO tope FROM contenido.tabla_conversion t JOIN contenido.prueba p ON p.id = t.prueba_id WHERE t.id = tid;
    IF n <> maximo + 1 THEN RAISE EXCEPTION 'La tabla de conversión debe ir de 0 a % correctas sin saltos', maximo; END IF;
    IF maximo > tope THEN RAISE EXCEPTION 'La tabla llega a % correctas y en la prueba cuentan %', maximo, tope; END IF;
    SELECT COUNT(*) INTO bajan FROM (SELECT puntaje < LAG(puntaje) OVER (ORDER BY correctas) AS baja
                                       FROM contenido.tabla_conversion_fila WHERE tabla_conversion_id = tid) x WHERE baja;
    IF bajan > 0 THEN RAISE EXCEPTION 'En la tabla de conversión el puntaje no puede bajar al aumentar las correctas'; END IF;
  END LOOP;
  RETURN NULL;
END $$;
CREATE CONSTRAINT TRIGGER tabla_conversion_fila_completa AFTER INSERT OR UPDATE OR DELETE ON contenido.tabla_conversion_fila
  DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION contenido.tg_tabla_conversion_fila();

-- ----- Correos de verificación y recuperación (RN-32). Al pedir uno nuevo, el anterior del mismo tipo deja de servir.
-- Solo el tipo que admite código lo guarda (cifrado). Los intentos fallidos solo suben y no pasan el máximo del tipo.
-- Un correo usado o anulado no cambia, y el enlace y el código guardados no se modifican.
CREATE FUNCTION app.tg_token_correo() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE tt contenido.tipo_token_correo%ROWTYPE;
BEGIN
  SELECT * INTO tt FROM contenido.tipo_token_correo WHERE id = NEW.tipo_token_correo_id;
  IF TG_OP = 'INSERT' THEN
    IF (NEW.hash_codigo IS NOT NULL) <> (tt.intentos_codigo IS NOT NULL) THEN
      RAISE EXCEPTION 'El correo «%» % lleva código', tt.nombre, CASE WHEN tt.intentos_codigo IS NULL THEN 'no' ELSE 'sí' END;
    END IF;
    IF NEW.usado_en IS NOT NULL OR NEW.anulado_en IS NOT NULL OR NEW.intentos_fallidos <> 0 THEN
      RAISE EXCEPTION 'Un correo nuevo parte sin usar y sin intentos';
    END IF;
    UPDATE app.token_correo SET anulado_en = now()
     WHERE estudiante_id = NEW.estudiante_id AND tipo_token_correo_id = NEW.tipo_token_correo_id AND usado_en IS NULL AND anulado_en IS NULL;
    RETURN NEW;
  END IF;
  IF OLD.usado_en IS NOT NULL OR OLD.anulado_en IS NOT NULL THEN
    RAISE EXCEPTION 'Un correo usado o anulado ya no sirve';
  END IF;
  IF (NEW.estudiante_id, NEW.tipo_token_correo_id, NEW.hash_token, NEW.hash_codigo, NEW.expira_en)
     IS DISTINCT FROM (OLD.estudiante_id, OLD.tipo_token_correo_id, OLD.hash_token, OLD.hash_codigo, OLD.expira_en) THEN
    RAISE EXCEPTION 'El enlace y el código de un correo enviado no se modifican';
  END IF;
  IF NEW.intentos_fallidos < OLD.intentos_fallidos THEN RAISE EXCEPTION 'Los intentos fallidos no se descuentan'; END IF;
  IF NEW.intentos_fallidos > COALESCE(tt.intentos_codigo, 0) THEN
    RAISE EXCEPTION 'El código ya no sirve: se alcanzaron los % intentos; hay que pedir un correo nuevo', COALESCE(tt.intentos_codigo, 0);
  END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER token_correo_reglas BEFORE INSERT OR UPDATE ON app.token_correo
  FOR EACH ROW EXECUTE FUNCTION app.tg_token_correo();

-- ----- Racha (RF-A05): días seguidos, en hora de Chile, con al menos una pregunta respondida en cualquier práctica o
-- evaluación. Se actualiza con la primera respuesta de cada día.
CREATE FUNCTION app.tg_racha() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE dia DATE := (NEW.respondida_en AT TIME ZONE 'America/Santiago')::date;
BEGIN
  UPDATE app.estudiante es
     SET racha_dias = CASE WHEN es.ultimo_dia_practica = dia - 1 THEN es.racha_dias + 1 ELSE 1 END, ultimo_dia_practica = dia
    FROM app.evaluacion e
   WHERE e.id = NEW.evaluacion_id AND es.id = e.estudiante_id AND (es.ultimo_dia_practica IS NULL OR es.ultimo_dia_practica < dia);
  RETURN NULL;
END $$;
CREATE TRIGGER item_racha AFTER INSERT OR UPDATE OF respondida_en ON app.evaluacion_item
  FOR EACH ROW WHEN (NEW.respondida_en IS NOT NULL) EXECUTE FUNCTION app.tg_racha();

