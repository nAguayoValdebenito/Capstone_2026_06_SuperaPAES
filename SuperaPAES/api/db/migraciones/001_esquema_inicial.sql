JOIN contenido.pregunta_version v ON (v.pregunta_id, v.version) = (i.pregunta_id, i.version_pregunta)
WHERE te.cuenta_para_progreso AND i.es_correcta IS NOT NULL AND NOT i.anulada;

-- Progreso por eje: acierto por dificultad y acierto ponderado (las difíciles pesan más). Un eje es a reforzar si tiene
-- al menos min_respuestas_eje respuestas y su acierto ponderado es menor que umbral_eje_debil, salvo que el estudiante
-- todavía no lo vea en su curso.
CREATE VIEW app.v_progreso_eje AS
WITH por_dificultad AS (
  SELECT r.estudiante_id, r.prueba_id, r.eje_id, d.codigo, d.peso, COUNT(*) AS n, COUNT(*) FILTER (WHERE r.es_correcta) AS c
  FROM app.v_respuesta_valida r JOIN contenido.dificultad d ON d.id = r.dificultad_id
  GROUP BY 1, 2, 3, 4, 5),
ejes AS (
  SELECT estudiante_id, prueba_id, eje_id, SUM(n) AS respondidas, SUM(c) AS correctas,
         ROUND(100.0 * SUM(c * peso) / SUM(n * peso), 1) AS acierto_ponderado,
         jsonb_object_agg(codigo, ROUND(100.0 * c / n, 1)) AS acierto_por_dificultad
  FROM por_dificultad GROUP BY 1, 2, 3)
SELECT x.*,
       x.respondidas >= (SELECT (valor #>> '{}')::int FROM contenido.configuracion WHERE clave = 'min_respuestas_eje')
       AND x.acierto_ponderado < (SELECT (valor #>> '{}')::numeric FROM contenido.configuracion WHERE clave = 'umbral_eje_debil')
       AND EXISTS (SELECT 1 FROM contenido.contenido_tematico ct LEFT JOIN contenido.nivel_escolar nc ON nc.id = ct.nivel_escolar_id
                   JOIN app.estudiante es ON es.id = x.estudiante_id
                   LEFT JOIN contenido.nivel_escolar ne ON ne.id = app.nivel_escolar_en(es.anio_egreso, app.hoy_chile())
                   WHERE ct.eje_id = x.eje_id AND (nc.orden IS NULL OR ne.orden IS NULL OR nc.orden <= ne.orden)) AS a_reforzar
FROM ejes x;

-- Progreso por habilidad, con el mismo acierto ponderado.
CREATE VIEW app.v_progreso_habilidad AS
SELECT r.estudiante_id, r.prueba_id, r.habilidad_id, COUNT(*) AS respondidas, COUNT(*) FILTER (WHERE r.es_correcta) AS correctas,
       ROUND(100.0 * SUM(d.peso) FILTER (WHERE r.es_correcta) / SUM(d.peso), 1) AS acierto_ponderado
FROM app.v_respuesta_valida r JOIN contenido.dificultad d ON d.id = r.dificultad_id
GROUP BY 1, 2, 3;

-- Evolución semanal del acierto por prueba.
CREATE VIEW app.v_evolucion_semanal AS
SELECT estudiante_id, prueba_id, date_trunc('week', fecha)::date AS semana, COUNT(*) AS respondidas,
       ROUND(100.0 * COUNT(*) FILTER (WHERE es_correcta) / COUNT(*), 1) AS acierto
FROM app.v_respuesta_valida
GROUP BY 1, 2, 3;

-- Preguntas por repasar: aquellas cuya última respuesta del estudiante fue incorrecta u omitida (si dos respuestas
-- tienen la misma hora, cuenta la registrada después).
CREATE VIEW app.v_preguntas_falladas AS
SELECT estudiante_id, prueba_id, eje_id, pregunta_id, fecha
FROM (SELECT DISTINCT ON (estudiante_id, pregunta_id) * FROM app.v_respuesta_valida
      ORDER BY estudiante_id, pregunta_id, fecha DESC, evaluacion_item_id DESC) ultima
WHERE NOT es_correcta;

-- Suscripciones por plan, tienda y estado.
CREATE VIEW app.v_resumen_suscripciones AS
SELECT pl.id AS plan_id, pl.nombre AS plan, cv.codigo AS tienda, es.codigo AS estado, COUNT(*) AS suscripciones,
       COUNT(*) FILTER (WHERE s.creado_en >= date_trunc('month', now())) AS creadas_este_mes
FROM app.suscripcion s
JOIN contenido.plan pl ON pl.id = s.plan_id
JOIN contenido.canal_venta cv ON cv.id = s.canal_venta_id
JOIN contenido.estado_suscripcion es ON es.id = s.estado_suscripcion_id
GROUP BY pl.id, pl.nombre, cv.codigo, es.codigo;

-- Pagos e ingresos por mes, plan y tienda.
CREATE VIEW app.v_pagos_mes AS
SELECT date_trunc('month', p.periodo_inicio)::date AS mes, s.plan_id, cv.codigo AS tienda,
       COUNT(*) FILTER (WHERE ep.codigo = 'aprobado') AS pagos_aprobados,
       COUNT(*) FILTER (WHERE ep.codigo = 'rechazado') AS pagos_rechazados,
       COALESCE(SUM(p.monto_clp) FILTER (WHERE ep.codigo = 'aprobado'), 0) AS ingresos_clp
FROM app.pago p
JOIN app.suscripcion s ON s.id = p.suscripcion_id
JOIN contenido.canal_venta cv ON cv.id = s.canal_venta_id
JOIN contenido.estado_pago ep ON ep.id = p.estado_pago_id
GROUP BY 1, s.plan_id, cv.codigo;

