SELECT c.id AS criterio_id, c.codigo AS criterio,
       CASE WHEN p.lote_id IS NOT NULL THEN 'ia' WHEN p.importacion_id IS NOT NULL THEN 'importacion' ELSE 'manual' END AS origen,
       COUNT(*) AS evaluaciones, COUNT(*) FILTER (WHERE NOT rc.cumple) AS incumplidas,
