-- Respuestas que cuentan para el progreso, con la clasificación de la versión que vio el estudiante.
CREATE VIEW app.v_respuesta_valida AS
SELECT ev.estudiante_id, ev.prueba_id, v.eje_id, v.habilidad_id, v.dificultad_id, i.pregunta_id, i.es_correcta,
       COALESCE(i.respondida_en, ev.cerrada_en) AS fecha, i.id AS evaluacion_item_id
FROM app.evaluacion_item i
