-- Imágenes de las preguntas (HU-12.6, HU-13.4 y HU-16.6): imágenes y gráficos de las preguntas y de los textos de lectura.
-- Solo agrega la tabla contenido.imagen, del módulo preguntas, y la acción de auditoría subir_imagen: ninguna
-- tabla existente cambia, así que una versión anterior de la API sigue funcionando sobre esta base.
-- Las preguntas y los textos no apuntan a la imagen con una clave foránea: la nombran en su Markdown como
-- ![texto alternativo](recursos/imagenes/<huella>.webp). Por eso una imagen nunca se modifica ni se borra.
-- No editar este archivo después de aplicarlo: el migrador valida su suma SHA-256.

CREATE TABLE contenido.imagen (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  huella CHAR(64) NOT NULL UNIQUE,
  ancho SMALLINT NOT NULL,
  alto SMALLINT NOT NULL,
  bytes INTEGER NOT NULL,
  datos BYTEA NOT NULL,
  datos_grafico JSONB,
  importacion_id BIGINT,
  lote_id BIGINT,
  creado_por BIGINT NOT NULL,
  creado_en TIMESTAMPTZ NOT NULL,
  PRIMARY KEY (id),
  CHECK (huella ~ '^[0-9a-f]{64}$'),
  CHECK (ancho BETWEEN 1 AND 3200 AND alto BETWEEN 1 AND 3200),
  CHECK (bytes BETWEEN 1 AND 2097152 AND bytes = octet_length(datos)),
  CHECK (importacion_id IS NULL OR lote_id IS NULL),
  CHECK (datos_grafico IS NULL OR jsonb_typeof(datos_grafico) = 'object')
);

ALTER TABLE contenido.imagen ADD FOREIGN KEY (importacion_id) REFERENCES contenido.importacion (id) ON DELETE RESTRICT;
ALTER TABLE contenido.imagen ADD FOREIGN KEY (lote_id) REFERENCES contenido.lote_generacion (id) ON DELETE RESTRICT;
ALTER TABLE contenido.imagen ADD FOREIGN KEY (creado_por) REFERENCES contenido.usuario_interno (id) ON DELETE RESTRICT;

COMMENT ON TABLE contenido.imagen IS 'Imágenes y gráficos de las preguntas y de los textos de lectura, en WebP. No se modifican ni se borran: una imagen nueva es otra fila.';
COMMENT ON COLUMN contenido.imagen.huella IS 'SHA-256 en hexadecimal de los datos; forma la dirección recursos/imagenes/<huella>.webp. La misma imagen se guarda una sola vez.';
COMMENT ON COLUMN contenido.imagen.ancho IS 'Ancho en píxeles, después de reducirla o de dibujar el gráfico.';
COMMENT ON COLUMN contenido.imagen.alto IS 'Alto en píxeles, después de reducirla o de dibujar el gráfico.';
COMMENT ON COLUMN contenido.imagen.bytes IS 'Tamaño de los datos en bytes (hasta 2 MB).';
COMMENT ON COLUMN contenido.imagen.datos IS 'La imagen en WebP, ya reducida y sin metadatos.';
COMMENT ON COLUMN contenido.imagen.datos_grafico IS 'Datos validados con que el servidor dibujó el gráfico, para mostrárselos al docente; vacío en una imagen subida.';
COMMENT ON COLUMN contenido.imagen.importacion_id IS 'Importación de la que viene, con el origen declarado en ella (RN-29); vacío si no es importada.';
COMMENT ON COLUMN contenido.imagen.lote_id IS 'Lote de la IA cuyo gráfico dibujó el servidor; vacío si no viene de un lote.';
COMMENT ON COLUMN contenido.imagen.creado_por IS 'Administrador que la subió, la importó o pidió el lote.';

CREATE TRIGGER imagen_fija BEFORE UPDATE OR DELETE ON contenido.imagen
  FOR EACH ROW EXECUTE FUNCTION contenido.tg_solo_agregar();

INSERT INTO contenido.accion_auditoria (codigo, nombre) VALUES
  ('subir_imagen', 'Subir una imagen o un gráfico')
ON CONFLICT (codigo) DO NOTHING;
