-- Supera PAES. Migración del modelo de datos de la versión 11.0 a la 12.0.
-- 1. El historial de la suscripción (app.suscripcion_evento) guarda el plan anterior y el nuevo, admite un cambio de plan con el
--    mismo estado y no tiene saltos: cada registro parte del estado y el plan del anterior (RN-17).
-- 2. Vista app.v_item_evaluacion: lo que la API envía a la app de cada pregunta, sin la clave ni las explicaciones hasta que el
--    ítem se corrige (RN-06).
-- La tabla del historial se vuelve a crear para que quede igual a la del modelo 12.0, columna por columna. Solo se hace si aún no
-- tiene registros (todavía no hay suscripciones); si los tiene, la migración se detiene sin cambiar nada.

DO $$
BEGIN
  IF EXISTS (SELECT 1 FROM app.suscripcion_evento) THEN
    RAISE EXCEPTION 'app.suscripcion_evento ya tiene registros: esta migración solo se aplica con el historial vacío';
  END IF;
END $$;

DROP TABLE app.suscripcion_evento;
DROP FUNCTION app.tg_suscripcion_evento();

CREATE TABLE app.suscripcion_evento (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  suscripcion_id BIGINT NOT NULL,
  estado_anterior_id SMALLINT,
  estado_nuevo_id SMALLINT NOT NULL,
  plan_anterior_id SMALLINT,
  plan_nuevo_id SMALLINT NOT NULL,
  origen_evento_id SMALLINT NOT NULL,
  evento_pasarela_id BIGINT,
  detalle VARCHAR(200),
  creado_en TIMESTAMPTZ NOT NULL,
  PRIMARY KEY (id),
  CHECK ((estado_anterior_id IS NULL) = (plan_anterior_id IS NULL)),
  CHECK (estado_anterior_id IS NULL OR estado_anterior_id <> estado_nuevo_id OR plan_anterior_id <> plan_nuevo_id)
);

ALTER TABLE app.suscripcion_evento ADD FOREIGN KEY (suscripcion_id) REFERENCES app.suscripcion (id) ON DELETE RESTRICT;
ALTER TABLE app.suscripcion_evento ADD FOREIGN KEY (estado_anterior_id) REFERENCES contenido.estado_suscripcion (id) ON DELETE RESTRICT;
ALTER TABLE app.suscripcion_evento ADD FOREIGN KEY (estado_nuevo_id) REFERENCES contenido.estado_suscripcion (id) ON DELETE RESTRICT;
ALTER TABLE app.suscripcion_evento ADD FOREIGN KEY (plan_anterior_id) REFERENCES contenido.plan (id) ON DELETE RESTRICT;
ALTER TABLE app.suscripcion_evento ADD FOREIGN KEY (plan_nuevo_id) REFERENCES contenido.plan (id) ON DELETE RESTRICT;
ALTER TABLE app.suscripcion_evento ADD FOREIGN KEY (origen_evento_id) REFERENCES contenido.origen_evento (id) ON DELETE RESTRICT;
ALTER TABLE app.suscripcion_evento ADD FOREIGN KEY (evento_pasarela_id) REFERENCES app.evento_pasarela (id) ON DELETE RESTRICT;

CREATE INDEX ix_suscripcion_evento_linea ON app.suscripcion_evento (suscripcion_id, creado_en);

CREATE TRIGGER suscripcion_evento_fijo BEFORE UPDATE OR DELETE ON app.suscripcion_evento
  FOR EACH ROW EXECUTE FUNCTION contenido.tg_solo_agregar();

-- Un cambio provocado por un aviso de la tienda apunta a ese aviso, y los demás no.
-- El historial no tiene saltos (RN-17): el primer registro no tiene estado ni plan anterior, y cada registro siguiente
-- parte del estado y el plan con que terminó el anterior. Se bloquea la suscripción para que dos cambios no se crucen.
CREATE FUNCTION app.tg_suscripcion_evento() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE ultimo RECORD;
BEGIN
  IF (SELECT requiere_aviso FROM contenido.origen_evento WHERE id = NEW.origen_evento_id) <> (NEW.evento_pasarela_id IS NOT NULL) THEN
    RAISE EXCEPTION 'Un cambio provocado por la tienda apunta a su aviso, y los demás no';
  END IF;
  PERFORM 1 FROM app.suscripcion WHERE id = NEW.suscripcion_id FOR UPDATE;
  SELECT estado_nuevo_id, plan_nuevo_id INTO ultimo FROM app.suscripcion_evento
   WHERE suscripcion_id = NEW.suscripcion_id ORDER BY creado_en DESC, id DESC LIMIT 1;
  IF NOT FOUND THEN
    IF NEW.estado_anterior_id IS NOT NULL THEN
      RAISE EXCEPTION 'El primer registro de una suscripción no tiene estado ni plan anterior';
    END IF;
  ELSIF NEW.estado_anterior_id IS DISTINCT FROM ultimo.estado_nuevo_id OR NEW.plan_anterior_id IS DISTINCT FROM ultimo.plan_nuevo_id THEN
    RAISE EXCEPTION 'El estado y el plan anteriores deben ser los del último registro de la suscripción';
  END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER suscripcion_evento_reglas BEFORE INSERT ON app.suscripcion_evento
  FOR EACH ROW EXECUTE FUNCTION app.tg_suscripcion_evento();

-- Lo que la API envía a la app para mostrar cada pregunta de una evaluación (RN-06): enunciado, texto y alternativas de la
-- versión que vio el estudiante, sin la clave ni las explicaciones. La corrección, la alternativa correcta y las explicaciones
-- aparecen solo cuando el ítem ya está corregido: al responder en la práctica y el repaso, y al cerrar en las demás.
CREATE VIEW app.v_item_evaluacion AS
SELECT i.evaluacion_id, ev.estudiante_id, i.id AS evaluacion_item_id, i.orden, i.pregunta_id, i.version_pregunta, i.puntuable, i.anulada,
       v.copia ->> 'enunciado' AS enunciado, t.titulo AS texto_titulo, t.contenido AS texto_contenido, t.imagen_url AS texto_imagen_url,
       (SELECT jsonb_agg(jsonb_build_object('id', a -> 'id', 'letra', a -> 'letra', 'texto', a -> 'texto') ORDER BY a ->> 'letra')
          FROM jsonb_array_elements(v.copia -> 'alternativas') a) AS alternativas,
       i.alternativa_id AS alternativa_elegida, i.respondida_en, c.corregida,
       CASE WHEN c.corregida THEN i.es_correcta END AS es_correcta,
       CASE WHEN c.corregida THEN v.alternativa_correcta_id END AS alternativa_correcta_id,
       CASE WHEN c.corregida THEN v.copia ->> 'explicacion' END AS explicacion,
       CASE WHEN c.corregida THEN v.copia -> 'alternativas' END AS alternativas_con_explicacion
FROM app.evaluacion_item i
JOIN app.evaluacion ev ON ev.id = i.evaluacion_id
JOIN contenido.tipo_evaluacion te ON te.id = ev.tipo_evaluacion_id
JOIN contenido.pregunta_version v ON (v.pregunta_id, v.version) = (i.pregunta_id, i.version_pregunta)
LEFT JOIN contenido.texto_estimulo t ON t.id = (v.copia ->> 'texto_estimulo_id')::bigint
CROSS JOIN LATERAL (SELECT ev.cerrada_en IS NOT NULL OR (te.correccion_inmediata AND i.respondida_en IS NOT NULL) AS corregida) c;

COMMENT ON TABLE app.suscripcion_evento IS 'Historial de cada suscripción: un registro por cada cambio de estado o de plan, con lo que lo provocó. Nunca se modifica ni se borra, y es la base de la trazabilidad de suscripciones en la consola.';
COMMENT ON COLUMN app.suscripcion_evento.id IS 'Identificador del registro.';
COMMENT ON COLUMN app.suscripcion_evento.suscripcion_id IS 'Suscripción que cambió.';
COMMENT ON COLUMN app.suscripcion_evento.estado_anterior_id IS 'Estado antes del cambio. Vacío en el primer registro, cuando se crea la suscripción.';
COMMENT ON COLUMN app.suscripcion_evento.estado_nuevo_id IS 'Estado después del cambio.';
COMMENT ON COLUMN app.suscripcion_evento.plan_anterior_id IS 'Plan antes del cambio, incluida su periodicidad. Vacío en el primer registro, cuando se crea la suscripción.';
COMMENT ON COLUMN app.suscripcion_evento.plan_nuevo_id IS 'Plan después del cambio. Igual al anterior si solo cambió el estado.';
COMMENT ON COLUMN app.suscripcion_evento.origen_evento_id IS 'Qué provocó el cambio: el estudiante (al suscribirse o cancelar), un aviso de la tienda o una tarea automática del sistema, como el vencimiento.';
COMMENT ON COLUMN app.suscripcion_evento.evento_pasarela_id IS 'Aviso de la tienda que provocó el cambio. Obligatorio si el origen lo requiere y vacío en los demás casos.';
COMMENT ON COLUMN app.suscripcion_evento.detalle IS 'Explicación breve, por ejemplo el motivo del rechazo de un cobro.';
COMMENT ON COLUMN app.suscripcion_evento.creado_en IS 'Fecha y hora del cambio.';
