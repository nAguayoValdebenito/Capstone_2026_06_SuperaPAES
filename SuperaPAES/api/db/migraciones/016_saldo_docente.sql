CREATE FUNCTION contenido.tg_tarifa_revision_vigencia() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF NEW.vigente_desde < statement_timestamp() THEN
    RAISE EXCEPTION 'La tarifa no puede tener vigencia retroactiva' USING ERRCODE = '23514';
  END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER tarifa_revision_vigencia BEFORE INSERT ON contenido.tarifa_revision
FOR EACH ROW EXECUTE FUNCTION contenido.tg_tarifa_revision_vigencia();

CREATE FUNCTION contenido.tg_remuneracion_inmutable() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  RAISE EXCEPTION 'El historial de remuneraciones y tarifas no se modifica ni se borra';
END $$;
CREATE TRIGGER tarifa_revision_inmutable BEFORE UPDATE OR DELETE ON contenido.tarifa_revision
FOR EACH ROW EXECUTE FUNCTION contenido.tg_remuneracion_inmutable();
CREATE TRIGGER remuneracion_revision_inmutable BEFORE UPDATE OR DELETE ON contenido.remuneracion_revision
FOR EACH ROW EXECUTE FUNCTION contenido.tg_remuneracion_inmutable();

-- El mismo candado se toma antes de reservar preguntas y asignaciones en los repositorios.
-- Serializa las operaciones de asignación y entrega, incluidas las de áreas distintas.
CREATE FUNCTION contenido.capacidad_docente(p_docente BIGINT, p_momento TIMESTAMPTZ)
RETURNS TABLE(pendientes BIGINT, completadas BIGINT, max_pendientes INTEGER, max_diarias INTEGER)
LANGUAGE sql VOLATILE AS $$
  SELECT
    (SELECT count(*) FROM contenido.asignacion_revision a
       JOIN contenido.estado_asignacion e ON e.id = a.estado_asignacion_id
      WHERE a.docente_id = p_docente AND e.codigo = 'pendiente'),
    (SELECT count(*) FROM contenido.revision r
       JOIN contenido.asignacion_revision a ON a.id = r.asignacion_id
      WHERE a.docente_id = p_docente
        AND r.creado_en >= ((p_momento AT TIME ZONE 'America/Santiago')::date::timestamp AT TIME ZONE 'America/Santiago')
        AND r.creado_en < (((p_momento AT TIME ZONE 'America/Santiago')::date + 1)::timestamp AT TIME ZONE 'America/Santiago')),
    (SELECT (valor #>> '{}')::integer FROM contenido.configuracion WHERE clave = 'max_pendientes_docente'),
    (SELECT (valor #>> '{}')::integer FROM contenido.configuracion WHERE clave = 'max_revisiones_diarias_docente')
$$;

CREATE FUNCTION contenido.tg_asignacion_capacidad() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE c RECORD;
BEGIN
  PERFORM pg_advisory_xact_lock(6971);
  SELECT * INTO c FROM contenido.capacidad_docente(NEW.docente_id, NEW.asignado_en);
  IF c.max_pendientes IS NULL OR c.max_diarias IS NULL THEN
    RAISE EXCEPTION 'Falta la configuración de capacidad docente';
  END IF;
  IF c.pendientes >= c.max_pendientes OR c.completadas + c.pendientes >= c.max_diarias THEN
    RAISE EXCEPTION 'El docente no tiene cupo para recibir otra pregunta' USING ERRCODE = '23514';
  END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER asignacion_capacidad BEFORE INSERT ON contenido.asignacion_revision
FOR EACH ROW EXECUTE FUNCTION contenido.tg_asignacion_capacidad();

CREATE FUNCTION contenido.tg_revision_remuneracion() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE docente BIGINT; c RECORD; tarifa contenido.tarifa_revision%ROWTYPE;
BEGIN
  PERFORM pg_advisory_xact_lock(6971);
  SELECT docente_id INTO docente FROM contenido.asignacion_revision WHERE id = NEW.asignacion_id;
  SELECT * INTO c FROM contenido.capacidad_docente(docente, NEW.creado_en);
  -- AFTER INSERT: la revisión actual ya forma parte de completadas.
  IF c.completadas > c.max_diarias THEN
    RAISE EXCEPTION 'El docente alcanzó su máximo diario de revisiones' USING ERRCODE = '23514';
  END IF;
  SELECT * INTO tarifa FROM contenido.tarifa_revision WHERE vigente_desde <= NEW.creado_en
    ORDER BY vigente_desde DESC LIMIT 1;
  IF FOUND THEN
    INSERT INTO contenido.remuneracion_revision(revision_id, tarifa_id, monto_clp, fecha)
    VALUES (NEW.id, tarifa.id, tarifa.monto_clp, NEW.creado_en);
  END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER revision_remuneracion AFTER INSERT ON contenido.revision
FOR EACH ROW EXECUTE FUNCTION contenido.tg_revision_remuneracion();

CREATE TRIGGER revision_entregada_inmutable BEFORE UPDATE OR DELETE ON contenido.revision
FOR EACH ROW EXECUTE FUNCTION contenido.tg_remuneracion_inmutable();

CREATE FUNCTION contenido.tg_asignacion_entregada_identidad() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF (NEW.docente_id, NEW.pregunta_id, NEW.ronda, NEW.version_revisada, NEW.rol_revision_id)
     IS DISTINCT FROM (OLD.docente_id, OLD.pregunta_id, OLD.ronda, OLD.version_revisada, OLD.rol_revision_id)
     AND EXISTS (SELECT 1 FROM contenido.revision WHERE asignacion_id = OLD.id) THEN
    RAISE EXCEPTION 'La asignación de una revisión entregada no se modifica';
  END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER asignacion_entregada_identidad BEFORE UPDATE ON contenido.asignacion_revision
FOR EACH ROW EXECUTE FUNCTION contenido.tg_asignacion_entregada_identidad();

