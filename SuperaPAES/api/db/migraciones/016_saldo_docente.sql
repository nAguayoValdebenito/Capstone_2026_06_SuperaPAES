-- HU-69 a HU-71, RN-38 y RN-39. Los importes históricos son inmutables.
CREATE TABLE contenido.tarifa_revision (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  monto_clp INTEGER NOT NULL CHECK (monto_clp BETWEEN 1 AND 700),
  vigente_desde TIMESTAMPTZ NOT NULL UNIQUE,
  creado_en TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
  creado_por BIGINT REFERENCES contenido.usuario_interno(id) ON DELETE RESTRICT
);

CREATE TABLE contenido.remuneracion_revision (
  revision_id BIGINT PRIMARY KEY REFERENCES contenido.revision(id) ON DELETE RESTRICT,
  tarifa_id BIGINT NOT NULL REFERENCES contenido.tarifa_revision(id) ON DELETE RESTRICT,
  monto_clp INTEGER NOT NULL CHECK (monto_clp BETWEEN 1 AND 700),
  fecha TIMESTAMPTZ NOT NULL
);
CREATE INDEX remuneracion_revision_fecha ON contenido.remuneracion_revision(fecha, revision_id);
CREATE INDEX asignacion_revision_docente ON contenido.asignacion_revision(docente_id, estado_asignacion_id);
CREATE INDEX revision_fecha_asignacion ON contenido.revision(creado_en, asignacion_id);

