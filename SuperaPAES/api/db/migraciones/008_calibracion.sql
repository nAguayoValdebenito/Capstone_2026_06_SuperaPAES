-- Calibración de la dificultad (HU-26, RF-G13, RN-15; plan hu-26-calibracion.md, D3 opción A).
-- Solo agrega la tabla contenido.calibracion_pregunta, del módulo revision, y las acciones de auditoría
-- confirmar_calibracion y descartar_calibracion: ninguna tabla existente cambia, así que una versión
-- anterior de la API sigue funcionando sobre esta base.
-- Cada fila es la decisión de un docente sobre una pregunta que salió de su rango de acierto, para la
-- versión y la dificultad que tenía en ese momento. Una decisión no se modifica ni se borra: si la pregunta
-- cambia de versión o de dificultad tras una nueva revisión, la decisión siguiente es otra fila.
-- No editar este archivo después de aplicarlo: el migrador valida su suma SHA-256.

CREATE TABLE contenido.calibracion_pregunta (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  pregunta_id BIGINT NOT NULL,
  version_pregunta INTEGER NOT NULL,
  dificultad_id SMALLINT NOT NULL,
  docente_id BIGINT NOT NULL,
  dificultad_corresponde BOOLEAN NOT NULL,
  intentos INTEGER NOT NULL,
  aciertos INTEGER NOT NULL,
  creado_en TIMESTAMPTZ NOT NULL,
  PRIMARY KEY (id),
  UNIQUE (pregunta_id, version_pregunta, dificultad_id, docente_id),
  CHECK (intentos > 0 AND aciertos >= 0 AND aciertos <= intentos)
);

ALTER TABLE contenido.calibracion_pregunta ADD FOREIGN KEY (pregunta_id, version_pregunta) REFERENCES contenido.pregunta_version (pregunta_id, version) ON DELETE RESTRICT;
ALTER TABLE contenido.calibracion_pregunta ADD FOREIGN KEY (dificultad_id) REFERENCES contenido.dificultad (id) ON DELETE RESTRICT;
ALTER TABLE contenido.calibracion_pregunta ADD FOREIGN KEY (docente_id) REFERENCES contenido.usuario_interno (id) ON DELETE RESTRICT;

COMMENT ON TABLE contenido.calibracion_pregunta IS 'Decisión de cada docente sobre una pregunta de la bandeja de calibración (RN-15): si su dificultad corresponde o no al porcentaje de acierto. No se modifica ni se borra.';
COMMENT ON COLUMN contenido.calibracion_pregunta.id IS 'Identificador.';
COMMENT ON COLUMN contenido.calibracion_pregunta.pregunta_id IS 'Pregunta calibrada.';
COMMENT ON COLUMN contenido.calibracion_pregunta.version_pregunta IS 'Versión de la pregunta que tenía al decidir; una versión nueva vuelve a la bandeja.';
COMMENT ON COLUMN contenido.calibracion_pregunta.dificultad_id IS 'Dificultad asignada que tenía al decidir.';
COMMENT ON COLUMN contenido.calibracion_pregunta.docente_id IS 'Docente especialista del área que decidió.';
COMMENT ON COLUMN contenido.calibracion_pregunta.dificultad_corresponde IS 'Falso si el docente confirma que la dificultad no corresponde (pasa al administrador); verdadero si la descarta.';
COMMENT ON COLUMN contenido.calibracion_pregunta.intentos IS 'Intentos que tenía la pregunta cuando el docente decidió.';
COMMENT ON COLUMN contenido.calibracion_pregunta.aciertos IS 'Aciertos que tenía la pregunta cuando el docente decidió.';
COMMENT ON COLUMN contenido.calibracion_pregunta.creado_en IS 'Fecha y hora de la decisión.';

CREATE TRIGGER calibracion_pregunta_fija BEFORE UPDATE OR DELETE ON contenido.calibracion_pregunta
  FOR EACH ROW EXECUTE FUNCTION contenido.tg_solo_agregar();

INSERT INTO contenido.accion_auditoria (codigo, nombre) VALUES
  ('confirmar_calibracion', 'Confirmar que la dificultad de una pregunta no corresponde'),
  ('descartar_calibracion', 'Descartar una pregunta de la bandeja de calibración')
ON CONFLICT (codigo) DO NOTHING;
